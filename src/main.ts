import { mkdir, writeFile } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { execSync } from "node:child_process";
import { basename, dirname, join, resolve } from "node:path";
import { daemonRequest } from "./daemon";

/** Accepted and ignored: daemons before the socket hand-off spliced it into the command. */
const LEGACY_AUTH_ARG = "--exocortex-auth-openai";

interface GeneratedImage {
  imageBase64: string;
  revisedPrompt: string | null;
}

function usage(): string {
  return `usage: image <command> [args]\n\ncommands:\n  generate [--json] [--out <path>]   Generate an image from a prompt on stdin\n  help, -h, --help                   Show this help\n\nPrompt input:\n  image generate reads the exact UTF-8 prompt from stdin.\n  Inline prompt arguments are not accepted.\n\nThe image is generated by exocortexd with its own OpenAI login.`;
}

function generateUsage(): string {
  return `usage: image generate [--json] [--out <path>]\n\nGenerate an image and print the saved path.\n\nPrompt input:\n  The exact UTF-8 prompt is required on stdin.\n  Inline prompt arguments are not accepted.\n\noptions:\n  --json        Print structured output\n  --out <path>  Save the generated image at this path\n  -h, --help    Show this help`;
}

function die(message: string, code = 1): never {
  console.error(`image: ${message}`);
  process.exit(code);
}

function parseGlobalArgs(argv: string[]): string[] {
  const rest: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i]!;
    if (arg === LEGACY_AUTH_ARG) { i++; continue; }
    if (arg.startsWith(`${LEGACY_AUTH_ARG}=`)) continue;
    rest.push(arg);
  }
  return rest;
}

export function parseGenerateArgs(args: string[]): { json: boolean; outPath: string | null } {
  let json = false;
  let outPath: string | null = null;
  for (let i = 0; i < args.length; i++) {
    const arg = args[i]!;
    if (arg === "--json") {
      json = true;
    } else if (arg === "--out") {
      outPath = args[++i] ?? null;
      if (!outPath) die("--out requires a path");
    } else if (arg.startsWith("--out=")) {
      outPath = arg.slice("--out=".length);
      if (!outPath) die("--out requires a path");
    } else if (arg === "-h" || arg === "--help") {
      console.log(generateUsage());
      process.exit(0);
    } else {
      die("generate prompt must be provided via stdin; inline prompt is not accepted", 2);
    }
  }
  return { json, outPath };
}

export function decodePrompt(bytes: Uint8Array): string {
  if (bytes.byteLength === 0) die("generate prompt is required on stdin", 2);
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch {
    die("generate prompt on stdin must be valid UTF-8", 2);
  }
}

async function readPromptFromStdin(): Promise<string> {
  const chunks: Uint8Array[] = [];
  for await (const chunk of process.stdin) {
    chunks.push(typeof chunk === "string" ? Buffer.from(chunk) : chunk);
  }
  return decodePrompt(Buffer.concat(chunks));
}

async function generateImage(prompt: string): Promise<GeneratedImage> {
  const result = await daemonRequest<{ imageBase64?: unknown; revisedPrompt?: unknown }>(
    { type: "generate_image", prompt },
    "image_generation_result",
  );
  if (typeof result.imageBase64 !== "string" || result.imageBase64 === "") throw new Error("exocortexd returned no image data");
  return { imageBase64: result.imageBase64, revisedPrompt: typeof result.revisedPrompt === "string" ? result.revisedPrompt : null };
}

function repoRoot(): string {
  return resolve(import.meta.dir, "../../..");
}

function worktreeName(): string | null {
  try {
    const gitDir = execSync("git rev-parse --git-dir", { cwd: repoRoot(), encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
    const commonDir = execSync("git rev-parse --git-common-dir", { cwd: repoRoot(), encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
    if (resolve(repoRoot(), gitDir) !== resolve(repoRoot(), commonDir)) return basename(gitDir);
  } catch { /* not a git checkout */ }
  return null;
}

function dataDir(): string {
  const configRoot = process.env.EXOCORTEX_CONFIG_DIR?.trim()
    ? resolve(process.env.EXOCORTEX_CONFIG_DIR)
    : join(repoRoot(), "config");
  const wt = worktreeName();
  return wt ? join(configRoot, "data", "instances", wt) : join(configRoot, "data");
}

function sniffImageMediaType(bytes: Uint8Array): string {
  if (bytes.length >= 8 && bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4E && bytes[3] === 0x47 && bytes[4] === 0x0D && bytes[5] === 0x0A && bytes[6] === 0x1A && bytes[7] === 0x0A) return "image/png";
  if (bytes.length >= 3 && bytes[0] === 0xFF && bytes[1] === 0xD8 && bytes[2] === 0xFF) return "image/jpeg";
  if (bytes.length >= 6) {
    const head = Buffer.from(bytes.subarray(0, 6)).toString("ascii");
    if (head === "GIF87a" || head === "GIF89a") return "image/gif";
  }
  if (bytes.length >= 12) {
    const riff = Buffer.from(bytes.subarray(0, 4)).toString("ascii");
    const webp = Buffer.from(bytes.subarray(8, 12)).toString("ascii");
    if (riff === "RIFF" && webp === "WEBP") return "image/webp";
  }
  return "image/png";
}

function extensionForMediaType(mediaType: string): string {
  switch (mediaType) {
    case "image/jpeg": return "jpg";
    case "image/gif": return "gif";
    case "image/webp": return "webp";
    case "image/png":
    default: return "png";
  }
}

async function saveGeneratedImage(bytes: Uint8Array, mediaType: string, outPath: string | null): Promise<string> {
  const filePath = outPath
    ? resolve(outPath)
    : join(dataDir(), "generated-images", `${Date.now()}-${randomUUID().slice(0, 8)}.${extensionForMediaType(mediaType)}`);
  await mkdir(dirname(filePath), { recursive: true });
  await writeFile(filePath, bytes);
  return filePath;
}

async function main(): Promise<void> {
  const rest = parseGlobalArgs(process.argv.slice(2));
  const cmd = rest.shift();
  if (!cmd || cmd === "help" || cmd === "-h" || cmd === "--help") {
    console.log(usage());
    return;
  }
  if (cmd !== "generate") die(`unknown command '${cmd}'. Run image -h for usage.`);

  const { json, outPath } = parseGenerateArgs(rest);
  const prompt = await readPromptFromStdin();
  const generated = await generateImage(prompt);
  const bytes = Buffer.from(generated.imageBase64, "base64");
  if (bytes.length === 0) throw new Error("OpenAI image generation returned empty image data");
  const mediaType = sniffImageMediaType(bytes);
  const savedPath = await saveGeneratedImage(bytes, mediaType, outPath);

  if (json) {
    console.log(JSON.stringify({ path: savedPath, mediaType, revisedPrompt: generated.revisedPrompt }, null, 2));
  } else {
    console.log(savedPath);
  }
}

if (import.meta.main) main().catch((err) => die(err instanceof Error ? err.message : String(err)));
